// after styles.css: the shared AI panel skin overrides the per-app panel look
import '@genoffice/ui/ai-panel.css'
import '@genoffice/ui/ai-dock-narrow.css'
import { applyAiPanelPrefs, installScreenTips } from '@genoffice/ui'
import { mirrorUniworkAiFlag } from '@genoffice/ai-provider/browser'

installScreenTips()
// this renderer's own provider list shows the UniWork AI entry only while the shell offers it
mirrorUniworkAiFlag()

function applyTheme(theme: UiTheme): void {
  if (theme === 'system') document.documentElement.removeAttribute('data-theme')
  else document.documentElement.setAttribute('data-theme', theme)
}

void (async () => {
  const [lang, theme] = await Promise.all([
    window.pdfApi.getLanguage().catch(() => 'zh' as const),
    window.pdfApi.getTheme().catch(() => 'system' as const),
  ])
  document.documentElement.lang = htmlLang(lang as Lang)
  document.documentElement.dir = htmlDir(lang)
  applyTheme(theme)
  window.pdfApi.onThemeChanged(applyTheme)
  await window.pdfApi
    ?.getAiPanelPrefs?.()
    .then(applyAiPanelPrefs)
    .catch(() => {})
  window.pdfApi?.onAiPanelPrefsChanged?.(applyAiPanelPrefs)
  createRoot(document.getElementById('root')!).render(
    <LocaleProvider initial={lang}>
      <App />
    </LocaleProvider>,
  )
})()
