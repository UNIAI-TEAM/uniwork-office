import type { Lang } from '@genoffice/i18n'

export interface AiModelPickerStrings {
  /** chip tooltip / list heading */
  title: string
  /** chip text while no provider is usable yet */
  choose: string
  /** last row: jump to Settings › AI Model */
  manage: string
  /** composer hint while a key is stored but no model is known (send is off until one is picked) */
  needModel: string
  /** composer hint while no key is stored (send is off until one is added in the AI settings) */
  needKey: string
  /** composer hint while a custom endpoint has a model but no server URL (its API key is optional) */
  needBaseUrl: string
  /** S7 desktop picker footer: plan does not include UniWork AI */
  cloudStateNotEntitled: string
  /** S7 desktop picker footer: organization subscription is inactive */
  cloudStateInactive: string
  /** S7 desktop picker footer: organization AI credits are exhausted */
  cloudStateExhausted: string
  /** S7 desktop picker footer: UniWork cloud AI is unavailable (cloud_unavailable) */
  cloudStateUnavailable: string
  /** S7 desktop provider row visible credits sub-line ({remaining} / {limit}) */
  cloudCreditsLeft: string
  /** S7 desktop provider row credits when limit is null */
  cloudCreditsUnlimited: string
  /** S7 desktop picker footer action when signed out */
  acctSignIn: string
  /** quiet note in a group while its live model list is still loading (the suggested list shows meanwhile) */
  modelsLoading: string
  /** quiet note in a group whose live model list could not be loaded (the suggested list shows instead) */
  modelsUnavailable: string
  /** quiet tag on a group/row whose requests use the key saved on UniWork */
  orgKeyTag: string
  /** tooltip and first-use privacy note for a group served by a key saved on UniWork */
  orgKeyNote: string
  /** Settings hint above Model while the provider is served by a key saved on UniWork (replaces the own-key chat hint) */
  orgKeyChatHint: string
  /** Settings link to manage keys saved on UniWork in the web app */
  orgKeyManage: string
  /** Settings action on a row served by a key on UniWork: type a key stored on this computer instead */
  orgKeyUseLocal: string
  /** Settings action that drops that typed key and goes back to the key saved on UniWork */
  orgKeyUseLocalCancel: string
}

